/**
 * LACPForge Pro - Multi-Platform Configuration Synthesizer
 * Generates verified production syntax for:
 * 1. Cisco IOS-XE / NX-OS
 * 2. Arista EOS
 * 3. Juniper Junos
 * 4. Linux (bond0 / systemd-networkd)
 * 5. Prometheus Telemetry Alerting Rules
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.LACPConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function generateCisco(cfg) {
    const lines = [];
    const minLinks = cfg.minLinks || 2;
    const rateFast = cfg.actorTimeoutShort ? 'lacp rate fast' : 'lacp rate normal';
    const hashCmd = cfg.hashAlgorithm === 'L3_L4' ? 'port-channel load-balance src-dst-ip-port' : (cfg.hashAlgorithm === 'L2_L3' ? 'port-channel load-balance src-dst-ip' : 'port-channel load-balance src-dst-mac');

    lines.push('! ==============================================================================');
    lines.push('! Cisco IOS-XE / NX-OS Hardened LACP Port-Channel Configuration');
    lines.push('! Generated by LACPForge Pro v1.0.0 (IEEE 802.1AX & IEEE 802.3ad)');
    lines.push('! ==============================================================================');
    lines.push('!');
    lines.push(`! Global Load-Balancing Policy (5-tuple L3+L4)`);
    lines.push(hashCmd);
    lines.push('!');
    lines.push('interface Port-Channel10');
    lines.push(' description 800G Data Center Backbone Uplink');
    lines.push(' switchport mode trunk');
    lines.push(' switchport trunk allowed vlan 10,20,100,200');
    lines.push(` ${rateFast}`);
    lines.push(` lacp min-links ${minLinks}`);
    if (cfg.suspendIndividual) {
      lines.push(' lacp suspend-individual');
    }
    lines.push(' mtu 9216');
    lines.push('!');
    lines.push('! --- Member Interfaces ---');
    lines.push('interface range HundredGigE1/0/1 - 8');
    lines.push(' description Member Links of Port-Channel10');
    lines.push(' mtu 9216');
    lines.push(' channel-group 10 mode active');
    lines.push('!');
    return lines.join('\n');
  }

  function generateArista(cfg) {
    const lines = [];
    const minLinks = cfg.minLinks || 2;
    const rateFast = cfg.actorTimeoutShort ? 'lacp rate fast' : 'lacp rate normal';

    lines.push('! ==============================================================================');
    lines.push('! Arista EOS Hardened LACP Port-Channel Configuration');
    lines.push('! Generated by LACPForge Pro v1.0.0');
    lines.push('! ==============================================================================');
    lines.push('!');
    lines.push('port-channel load-balance fields ip-port');
    lines.push('!');
    lines.push('interface Port-Channel10');
    lines.push('   description Leaf-Spine Interconnect Bundle');
    lines.push('   switchport mode trunk');
    lines.push(`   ${rateFast}`);
    lines.push(`   port-channel min-links ${minLinks}`);
    lines.push('   mtu 9216');
    lines.push('!');
    lines.push('interface Ethernet1-8');
    lines.push('   comment Physical Members of Port-Channel10');
    lines.push('   channel-group 10 mode active');
    lines.push('   mtu 9216');
    lines.push('!');
    return lines.join('\n');
  }

  function generateJunos(cfg) {
    const lines = [];
    const minLinks = cfg.minLinks || 2;
    const periodicRate = cfg.actorTimeoutShort ? 'fast' : 'slow';

    lines.push('# ==============================================================================');
    lines.push('# Juniper Junos Aggregated Ethernet (ae0) LACP Configuration');
    lines.push('# Generated by LACPForge Pro v1.0.0');
    lines.push('# ==============================================================================');
    lines.push('');
    lines.push('set chassis aggregated-devices ethernet device-count 8');
    lines.push('');
    lines.push('set interfaces ae0 description "800G Core Backbone Bundle"');
    lines.push('set interfaces ae0 aggregated-ether-options lacp active');
    lines.push(`set interfaces ae0 aggregated-ether-options lacp periodic ${periodicRate}`);
    lines.push(`set interfaces ae0 aggregated-ether-options minimum-links ${minLinks}`);
    lines.push('set interfaces ae0 mtu 9216');
    lines.push('set interfaces ae0 unit 0 family ethernet-switching interface-mode trunk');
    lines.push('set interfaces ae0 unit 0 family ethernet-switching vlan members [ 10 20 100 200 ]');
    lines.push('');
    lines.push('# Member Interfaces');
    lines.push('set interfaces et-0/0/0:0 ether-options 802.3ad ae0');
    lines.push('set interfaces et-0/0/1:0 ether-options 802.3ad ae0');
    lines.push('');
    lines.push('# 5-Tuple L3+L4 Hash Load-Balancing Policy');
    lines.push('set forwarding-options hash-key family inet layer-3');
    lines.push('set forwarding-options hash-key family inet layer-4');
    return lines.join('\n');
  }

  function generateLinux(cfg) {
    const lines = [];
    const minLinks = cfg.minLinks || 2;
    const lacpRate = cfg.actorTimeoutShort ? 'fast' : 'slow';
    const hashPolicy = cfg.hashAlgorithm === 'L3_L4' ? 'layer3+4' : (cfg.hashAlgorithm === 'L2_L3' ? 'layer2+3' : 'layer2');

    lines.push('# ==============================================================================');
    lines.push('# Linux / Cumulus Linux 802.3ad LACP Bond Configuration (/etc/network/interfaces)');
    lines.push('# Generated by LACPForge Pro v1.0.0');
    lines.push('# ==============================================================================');
    lines.push('');
    lines.push('auto bond0');
    lines.push('iface bond0 inet manual');
    lines.push('    bond-slaves eth1 eth2 eth3 eth4');
    lines.push('    bond-mode 802.3ad');
    lines.push('    bond-miimon 100');
    lines.push(`    bond-lacp-rate ${lacpRate}`);
    lines.push(`    bond-xmit-hash-policy ${hashPolicy}`);
    lines.push(`    bond-min-links ${minLinks}`);
    lines.push('    mtu 9216');
    return lines.join('\n');
  }

  function generatePrometheus(cfg) {
    return `# ==============================================================================
# Prometheus Link Aggregation & LACP Telemetry Alerting Rules
# Generated by LACPForge Pro v1.0.0
# ==============================================================================

groups:
  - name: lacp_telemetry_alerts
    rules:
      - alert: LACPMemberLinkDownAlert
        expr: (lacp_port_channel_configured_members - lacp_port_channel_active_members) > 0
        for: 30s
        labels:
          severity: warning
          tier: layer2-fabric
        annotations:
          summary: "LACP Member Link Down on {{ $labels.instance }}"
          description: "Port-channel {{ $labels.interface }} has degraded member links. Operating with reduced capacity."

      - alert: LACPPortChannelDegradedAlert
        expr: lacp_port_channel_active_members < lacp_port_channel_min_links
        for: 15s
        labels:
          severity: critical
          tier: layer2-fabric
        annotations:
          summary: "LACP Bundle Dropped Below Min-Links Threshold!"
          description: "Port-channel {{ $labels.interface }} active links fallen below SLA min-links. Bundle brought down to trigger ECMP failover."

      - alert: LACPMemberFlapRateHigh
        expr: rate(lacp_state_transitions_total[2m]) > 4
        for: 1m
        labels:
          severity: critical
          tier: physical-layer
        annotations:
          summary: "High LACP State Flapping on {{ $labels.interface }}"
          description: "LACP state machine transitioning rapidly. Probable optical transceiver fault, dirty fiber patch, or timer mismatch."

      - alert: LACPStateDesyncAlert
        expr: (lacp_actor_state{flag="collecting"} != lacp_partner_state{flag="distributing"})
        for: 10s
        labels:
          severity: critical
          tier: data-plane
        annotations:
          summary: "LACP Collecting/Distributing Desynchronization Detected!"
          description: "Actor Collecting state does not match Partner Distributing state on {{ $labels.interface }}. High risk of unidirectional packet blackholing."
`;
  }

  return {
    generateCisco,
    generateArista,
    generateJunos,
    generateLinux,
    generatePrometheus
  };
}));
